async def get_messages_chat_by_id(tg_client, chat_id: int, limit: int = 50):
    """
    Получить последние сообщения из чата по его chat_id.
    Вызывай, когда просят прочитать, пересказать, проверить или найти что-то в переписке.
    Если chat_id неизвестен, сначала вызови get_dialogs. Не выдумывай ID.

    Args:
        tg_client: Служебный параметр, подставляется автоматически. Не заполняй.
        chat_id: Числовой ID чата из поля ID результата get_dialogs.
        limit: Сколько последних сообщений вернуть. По умолчанию 50; для краткого пересказа хватит 20–30.

    Returns:
        Список последних сообщений чата.
    """
    return await tg_client.get_messages(chat_id, limit=limit)