async def send_message_by_chat_id(tg_client, chat_id: int, message: str):
    """
    Отправить сообщение в чат от имени владельца.
    Вызывай сразу, когда просят кому-то написать, без лишних подтверждений.
    Если chat_id неизвестен, сначала вызови get_dialogs и найди чат по имени. Не выдумывай ID.
    Текст пиши так, как просил владелец, без своих колкостей и подписи.

    Args:
        tg_client: Служебный параметр, подставляется автоматически. Не заполняй.
        chat_id: Числовой ID чата из поля ID результата get_dialogs.
        message: Готовый текст сообщения, ровно то, что нужно отправить.

    Returns:
        Ничего. После отправки коротко сообщи владельцу, что сообщение ушло.
    """
    await tg_client.send_message(chat_id, message=message)